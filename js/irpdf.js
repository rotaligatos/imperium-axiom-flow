// Incident report forms as PDF, blank (for paper filing) or filled from a report in the app.
//  General: "INCIDENT REPORT (IR)" (letter), as used by MSSI / WCLI / CWLI.
//  IT: "IT INCIDENT REPORT FORM" FO-MIS-02 rev. 0 (A4).
import { Pdf } from "./pdf.js";
import { LOGOS } from "./logos.js";

export const COMPANY_NAMES = { MSSI: "Module Systems and Services, Inc.", WCLI: "World Class Laminate, Inc.", CWLI: "Cebu World Laminate Inc." };
export const NATURE = [
  ["Health & Safety", [["injury_illness", "Injury/ illness"], ["damage_property", "Damage to property"], ["damage_environment", "Damage to environment"]]],
  ["Company Policy", [["code_of_discipline", "Code of discipline"], ["violence_aggression", "Violence/ aggression"], ["sop", "SOP"]]],
  ["Procedural/ Non Conformance", [["documentation_error", "Documentation error"], ["operational_error", "Operational error"], ["miscommunication", "Miscommunication"]]],
  ["Others", [["client_related", "Client-related"], ["service_provider", "Service provider"], ["third_party", "Third party"], ["others", "others"]]],
];
export const IT_ASSETS = [["laptop", "Laptop"], ["desktop", "Desktop"], ["account", "Account (specify)"]];
export const IT_TYPES = [["physical_damage", "Physical Damage"], ["file_loss", "File Loss/Corruption"], ["theft", "Theft"], ["malware", "Malware Infection"], ["hacked", "System/Account Hacked"], ["others", "Others (specify)"]];
export const ROLE_LABEL = { noted_by: "Noted by (supervisor)", dept_head: "Noted by (department head)", supervisor: "Immediate supervisor", manager: "Department manager",
  it_rep: "IT representative", it_manager: "IT Manager" };

const logoCache = {};
const logoFor = (c) => (LOGOS[c] ? (logoCache[c] ||= Pdf.logo(LOGOS[c])) : null);
const day = (iso) => { if (!iso) return ""; const x = new Date(/^\d{4}-\d\d-\d\d$/.test(iso) ? iso + "T00:00:00" : iso); return isNaN(x) ? String(iso) : x.toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" }); };
const when = (iso) => { if (!iso) return ""; const x = new Date(iso); return isNaN(x) ? "" : `${day(iso)} ${x.toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit" })}`; };
const GREY = [90, 90, 90], YEL = [255, 255, 0];

function logo(p, code, x, y, bw, bh) {
  const lg = logoFor(code);
  if (lg) { const sc = Math.min(bw / lg.w, bh / lg.h); p.image(lg, x, y + (bh - lg.h * sc) / 2, lg.w * sc, lg.h * sc); }
  else if (COMPANY_NAMES[code]) p.text(COMPANY_NAMES[code], x, y + bh / 2 + 3, { size: 9, bold: true });
}
function footer(p, d, W, H) {
  const t = `${COMPANY_NAMES[d.company] || d.company_name || ""}${d.ref_no ? " - " + d.ref_no : ""} - ${d.blank ? "blank form" : "generated by Imperium Axiom Flow"}`;
  p.text(t, W / 2, H - 22, { size: 6, align: "center", rgb: [120, 120, 120] });
}
// one signature block: label, name, title, small stamp; centred in [x, x+w]
function sigBlock(p, x, y, w, label, s) {
  p.text(label, x + 4, y + 10, { size: 8 });
  p.line(x + 10, y + 42, x + w - 10, y + 42, 0.5);
  if (!s) return;
  if (s.name) p.text(p.fit(s.name, 8.5, false, w - 12), x + w / 2, y + 39, { size: 8.5, align: "center" });
  if (s.title) p.text(p.fit(s.title, 8, true, w - 12), x + w / 2, y + 51, { size: 8, bold: true, align: "center" });
  if (s.stamp) p.text(p.fit(s.stamp, 5.6, false, w - 8), x + w / 2, y + 59, { size: 5.6, align: "center", rgb: GREY });
}

// ------------------------------------------------------------------ General IR (letter)
export function buildGeneralIrPdf(d) {
  const W = 612, H = 792, L = 36, R = 576, CW = R - L, LH = 12.5, BOTTOM = H - 40;
  const p = new Pdf(W, H); let y = 0;
  const head = () => {
    logo(p, d.company, L, 22, 160, 36);
    p.text("INCIDENT REPORT (IR)", 360, 50, { size: 17, bold: true, align: "center" });
    p.text("To be completed within Twenty Four (24) hours after the incident", 150, 66, { size: 7, bold: true });
    if (d.ref_no) p.text(d.ref_no, R, 30, { size: 8, bold: true, align: "right" });
    y = 72; footer(p, d, W, H);
  };
  const page = () => { p.newPage(); head(); };
  head();
  const row = (a, av, b, bv) => {
    p.rect(L, y, CW, 14); p.line(L + CW / 2, y, L + CW / 2, y + 14);
    p.text(a + " " + p.fit(av || "", 8.5, false, CW / 2 - p.width(a + " ", 8.5) - 8), L + 3, y + 10, { size: 8.5 });
    p.text(b + " " + p.fit(bv || "", 8.5, false, CW / 2 - p.width(b + " ", 8.5) - 8), L + CW / 2 + 3, y + 10, { size: 8.5 });
    y += 14;
  };
  const involved = [d.employee, d.persons_other].filter(Boolean).join(", ");
  row("Date Prepared:", d.blank ? "" : day(d.created_at), "Person/s Involved:", involved);
  row("Area of Incident:", d.location, "Date & Time of Incident:", d.blank ? "" : when(d.incident_at));
  // nature of incident
  { const wb = p.width("Nature of Incident ", 8.5, true), wn = p.width("(Check all that apply)", 8), sx = W / 2 - (wb + wn) / 2;
    p.rect(L, y, CW, 12); p.text("Nature of Incident", sx, y + 9, { size: 8.5, bold: true }); p.text("(Check all that apply)", sx + wb, y + 9, { size: 8 }); y += 12; }
  const cw = CW / 4, rows = Math.max(...NATURE.map(([, it]) => it.length)), nh = 11 + rows * 11 + 3, ns = new Set(d.nature || []);
  p.rect(L, y, CW, nh);
  NATURE.forEach(([g, items], i) => {
    const x = L + i * cw; p.text(g, x + cw / 2, y + 9, { size: 8, bold: true, align: "center" });
    items.forEach(([k, t], j) => { const yy = y + 13 + j * 11; p.check(x + 5, yy, 7, ns.has(k)); p.text(t, x + 16, yy + 6.5, { size: 8 }); });
  });
  y += nh;
  // a framed text area that can continue on the next page
  const area = (label, lines, minLines, after) => {
    let i = 0, first = true;
    for (;;) {
      const room = Math.floor((BOTTOM - y - 22) / LH);
      if (room < 3) { page(); continue; }
      const take = Math.min(room, Math.max(lines.length - i, first ? minLines : 0));
      const h = 18 + take * LH + 6;
      p.rect(L, y, CW, h); p.text(label + (first ? "" : " (continued)"), L + 3, y + 11, { size: 8.5, bold: true });
      for (let k = 0; k < take; k++) { const ln = lines[i + k]; if (ln) p.text(ln.t, L + 8, y + 18 + (k + 1) * LH - 3, { size: ln.s || 9.5, bold: !!ln.b }); }
      i += take; y += h; first = false;
      if (i >= lines.length) break;
      page();
    }
    if (after) after();
  };
  const para = (txt, size = 9.5, bold = false) => String(txt || "").split(/\n/).flatMap((ln) => (ln.trim() ? p.wrap(ln, size, bold, CW - 16).map((t) => ({ t, s: size, b: bold })) : [{ t: "" }]));
  const desc = d.blank ? [] : [...para(d.description), ...(d.witnesses ? [{ t: "" }, ...para("Witnesses: " + d.witnesses)] : []),
    ...(d.damage_amount != null ? para("Damage / loss: PHP " + Number(d.damage_amount).toLocaleString("en-PH", { minimumFractionDigits: 2 })) : [])];
  area("Concise/Brief Description of the Incident:", desc, d.blank ? 18 : 6);
  const corr = d.blank ? [{ t: "" }, { t: "" }, { t: "Responsible:", s: 8.5 }, { t: "" }, { t: "Target date of Completion:", s: 8.5 }]
    : [...para(d.corrective_action || "", 9, true), { t: "" }, { t: "Responsible:", s: 8.5 }, ...para(d.responsible || "", 9, true), { t: "" },
       { t: "Target date of Completion: " + (d.target_date ? day(d.target_date) : ""), s: 8.5 }];
  area("Corrective Action Report:", corr, 5);
  // IR status
  if (BOTTOM - y < 52) page();
  p.rect(L, y, CW, 50); p.text("IR Status:", L + 3, y + 11, { size: 8.5, bold: true });
  [["closed", "Closed"], ["open", "Open"], ["extended", "Extended"]].forEach(([k, t], i) => {
    const yy = y + 15 + i * 11; p.check(L + 20, yy, 7, !d.blank && d.ir_state === k); p.text(t, L + 32, yy + 6.5, { size: 8.5 });
    if (k === "extended") { p.line(L + 72, yy + 7.5, L + 200, yy + 7.5, 0.5); if (!d.blank && d.extended_to) p.text(day(d.extended_to), L + 75, yy + 6, { size: 8.5 }); }
  });
  y += 50;
  // signatures
  if (BOTTOM - y < 70) page();
  const noted = d.blank ? [{}] : (d.route_titles || []).filter((s) => ["noted_by", "dept_head", "supervisor", "manager"].includes(s.role));
  const cols = [["Prepared by:", d.blank ? null : { name: d.filer?.name || d.filed_by, title: d.filer?.position, stamp: `Filed in IAF ${when(d.created_at)}` }],
    ...(noted.length ? noted : [{}]).map((s) => ["Noted by:", d.blank || !s.name ? null : { name: s.name, title: s.title, stamp: s.acted_at ? `${s.action === "returned" ? "Returned" : "Endorsed"} in IAF ${when(s.acted_at)}` : "pending" }]),
    ["Received by (HR):", d.blank || !d.hr_received ? null : d.hr_received]];
  const sw = CW / cols.length;
  p.rect(L, y, CW, 64);
  cols.forEach(([lab, s], i) => sigBlock(p, L + i * sw, y, sw, lab, s));
  y += 64;
  return p.build({ title: `Incident Report ${d.ref_no || ""}` });
}

// ------------------------------------------------------------------ IT Incident Report FO-MIS-02 (A4)
export function buildItIrPdf(d) {
  const W = 595.28, H = 841.89, L = 40, R = 555, CW = R - L, LH = 13, BOTTOM = H - 40;
  const p = new Pdf(W, H); let y = 0; const it = d.it || {};
  const head = () => {
    logo(p, d.company, L, 22, 140, 40);
    p.text("IT INCIDENT REPORT FORM", W / 2, 54, { size: 13, bold: true, align: "center" });
    p.text("Control No.: FO-MIS-02", R, 34, { size: 8, align: "right" }); p.text("Revision No.: 0", R, 45, { size: 8, align: "right" }); p.text("Issue Date: 31MAR2026", R, 56, { size: 8, align: "right" });
    y = 70; footer(p, d, W, H);
  };
  const page = () => { p.newPage(); head(); };
  head();
  const lineField = (label, val, lx, x1, x2, yy, right = false) => {
    p.text(label, right ? x1 - 4 : lx, yy, { size: 8.5, align: right ? "right" : "left" });
    p.line(x1, yy + 2, x2, yy + 2, 0.5); if (val) p.text(p.fit(val, 8.5, false, x2 - x1 - 4), x1 + 2, yy, { size: 8.5 });
  };
  lineField("I.R Seq. No.", d.ref_no, 0, 420, R, y + 10, true); y += 13;
  lineField("Name", d.filer?.name || d.filed_by, L, 110, 280, y + 10); lineField("Date", d.blank ? "" : day(d.created_at), 0, 420, R, y + 10, true); y += 13;
  lineField("Position", d.filer?.position, L, 110, 280, y + 10); lineField("Department", d.filer?.department, 0, 420, R, y + 10, true); y += 18;
  const as = new Set(it.assets || []), ts = new Set(it.types || []);
  p.text("Affected Asset", L, y + 8, { size: 8.5, bold: true }); y += 11;
  [[0, 120], [1, 250], [2, 380]].forEach(([i, x]) => { p.check(x, y, 9, as.has(IT_ASSETS[i][0])); p.text(IT_ASSETS[i][1], x + 13, y + 7.5, { size: 8.5 }); });
  if (it.account_spec) p.text(p.fit(it.account_spec, 8, false, R - 470), 470, y + 7.5, { size: 8 });
  y += 14;
  p.text("Type of Incident", L, y + 8, { size: 8.5, bold: true }); y += 11;
  [0, 1, 2].forEach((j) => { [[j, 120], [j + 3, 380]].forEach(([i, x]) => { p.check(x, y + j * 11, 9, ts.has(IT_TYPES[i][0])); p.text(IT_TYPES[i][1], x + 13, y + j * 11 + 7.5, { size: 8.5 }); }); });
  if (it.others_spec) p.text(p.fit(it.others_spec, 8, false, R - 470), 470, y + 29.5, { size: 8 });
  y += 38;
  const para = (txt, size = 9) => String(txt || "").split(/\n/).flatMap((ln) => (ln.trim() ? p.wrap(ln, size, false, CW - 12).map((t) => ({ t })) : [{ t: "" }]));
  // ruled box that can continue on the next page
  const ruled = (label, lines, minLines, sub) => {
    let i = 0, first = true;
    for (;;) {
      const room = Math.floor((BOTTOM - y - 16) / LH);
      if (room < 3) { page(); continue; }
      const take = Math.min(room, Math.max(lines.length - i, first ? minLines : 0));
      const h = 13 + take * LH;
      p.rect(L, y, CW, h); p.line(L, y + 13, R, y + 13, 0.5); p.text(label + (first ? "" : " (continued)"), L + 3, y + 10, { size: 8.5, bold: true });
      for (let k = 0; k < take; k++) { const yy = y + 13 + (k + 1) * LH; if (k < take - 1) p.line(L, yy, R, yy, 0.3, [160, 160, 160]); const ln = lines[i + k]; if (ln && ln.t) p.text(ln.t, L + 4, yy - 3.5, { size: 9 }); }
      i += take; y += h; first = false;
      if (i >= lines.length) break;
      page();
    }
    if (sub) sub();
  };
  ruled("Description  / Symptoms", [{ t: "Date & Time: " + (d.blank ? "" : when(d.incident_at)) }, ...(d.blank ? [] : para(d.description))], 6);
  p.rect(L, y, CW, 11, { fill: YEL, stroke: [0, 0, 0], lw: 0.4 }); p.text("Please include photos and available documentary evidence of the incident.", L + 3, y + 8, { size: 8, rgb: [200, 0, 0] });
  y += 11;
  if (!d.blank && (d.files || []).length) { p.text(`${d.files.length} attachment(s) kept in IAF with this report.`, L + 3, y + 9, { size: 7.5, rgb: GREY }); y += 10; }
  if (BOTTOM - y < 70) page();
  const sup = (d.route_titles || []).find((s) => s.role === "supervisor");
  sigBlock(p, L, y + 6, 200, "", d.blank ? null : { name: d.filer?.name || d.filed_by, stamp: `Reported in IAF ${when(d.created_at)}` });
  sigBlock(p, R - 200, y + 6, 200, "", d.blank || !sup ? null : { name: sup.name, stamp: sup.acted_at ? `Endorsed in IAF ${when(sup.acted_at)}` : "pending" });
  p.text("Reported by", L + 100, y + 75, { size: 8.5, align: "center" }); p.text("Immediate Supervisor", R - 100, y + 75, { size: 8.5, align: "center" });
  y += 84;
  p.text("To be filled out by an IT Representative", L, y + 6, { size: 7 }); y += 10;
  if (BOTTOM - y < 50) page();
  p.rect(L, y, CW, 40); p.line(L, y + 13, R, y + 13, 0.5); p.text("Assessment", L + 3, y + 10, { size: 8.5, bold: true });
  lineField("Asset Tag:", it.asset_tag, L + 3, 110, 270, y + 24); lineField("Accountability Form No.:", it.accountability_no, 0, 440, R - 5, y + 24, true);
  lineField("Account:", it.account, L + 3, 110, 270, y + 36); lineField("Platform:", it.platform, 0, 440, R - 5, y + 36, true);
  y += 40;
  ruled("A. Findings", para(it.findings), 3);
  ruled("B. Business Impact", para(it.impact), 3);
  y += 6; ruled("Action Taken", para(it.action_taken), 3);
  y += 6; ruled("Recommendation", para(it.recommendation), 3);
  y += 6; if (BOTTOM - y < 30) page();
  p.rect(L, y, CW, 26); p.text("Status", L + 3, y + 10, { size: 8.5, bold: true });
  const stt = d.blank ? "" : it.it_status || "open";
  [["open", "Open", 120], ["ongoing", "Ongoing", 250], ["closed", "Closed/Date:", 380]].forEach(([k, t, x]) => { p.check(x, y + 13, 9, stt === k); p.text(t, x + 13, y + 20.5, { size: 8.5 }); });
  p.line(445, y + 22, R - 5, y + 22, 0.5); if (stt === "closed" && it.closed_on) p.text(day(it.closed_on), 448, y + 20, { size: 8.5 });
  y += 30;
  if (BOTTOM - y < 100) page();
  sigBlock(p, L, y + 8, 200, "", d.blank || !d.it_rep_name ? null : { name: d.it_rep_name, stamp: `Assessed in IAF ${when(d.it_rep_at)}` });
  sigBlock(p, R - 200, y + 8, 200, "", d.blank || !d.it_mgr_name ? null : { name: d.it_mgr_name, stamp: `Closed in IAF ${when(d.it_mgr_at)}` });
  p.text("IT Representative", L + 100, y + 77, { size: 8.5, align: "center" }); p.text("IT Manager", R - 100, y + 77, { size: 8.5, align: "center" });
  p.text("Date: " + (d.blank ? "" : day(d.it_rep_at)), L, y + 90, { size: 8.5 }); p.text("Date: " + (d.blank ? "" : day(d.it_mgr_at)), R - 200, y + 90, { size: 8.5 });
  return p.build({ title: `IT Incident Report ${d.ref_no || ""}` });
}

export function downloadPdf(bytes, name) {
  const url = URL.createObjectURL(new Blob([bytes], { type: "application/pdf" }));
  const a = document.createElement("a"); a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(url), 30000);
}
